  const QUOTE_PRIORITY = {
    u:["u1","u4","u2","u6","u5","u3"],
    r:["r3","r7","r1","r5","r4","r2"],
    m:["m2","m6","m4","m3","m1","m5"],
  };

  // ── 計分 ──
  const zoneKey = (v) => {
    const d = v - 50;
    if (Math.abs(d) <= 6) return "border";
    return (d < 0 ? "low-" : "high-") + (Math.abs(d) <= 20 ? "lean" : "vivid");
  };
  const ZONE_LABEL = { border:"交界", "low-lean":"傾向", "high-lean":"傾向", "low-vivid":"鮮明", "high-vivid":"鮮明" };
  const typeOf = (h) => TYPE_KEY[`${h.u ? 1 : 0}${h.r ? 1 : 0}${h.m ? 1 : 0}`];
  const has = (v) => v !== null && v !== undefined;

  function dimLabel(d, zone, high) {
    if (zone === "border") return DIMS[d].mid;
    return high ? DIMS[d].high : DIMS[d].low;
  }

  function calcResult(a) {
    const raw = { u:0, r:0, m:0 }, count = { u:0, r:0, m:0 }, scores = { u:[], r:[], m:[] };
    SCALE_QS.forEach((q, i) => {
      count[q.dim]++;
      if (!has(a.scale[i])) return;
      const s = q.opts[a.scale[i]].s;
      raw[q.dim] += s; scores[q.dim].push({ i, s });
    });
    const behav = a.behav || [];
    const source = has(behav[0]) ? BEHAV_QS[0].codes[behav[0]] : null;
    const behaviors = (Array.isArray(behav[1]) ? behav[1] : []).map(i => BEHAV_QS[1].codes[i]).filter(c => c !== "none");
    // 跟推薦的證據：清單有勾，或最近一次買進的來源是別人（兩者都有也只算一次）
    const followBy = SOURCE_FOLLOW.includes(source) ? source : behaviors.includes("follow") ? "list" : null;
    const selfSpectrum = {};
    ["u","r","m"].forEach(d => { selfSpectrum[d] = ((raw[d] - count[d]) / (3 * count[d])) * 100; });
    const behaviorAdjust = [];
    // 買進來源只當一題「借鑒他人」的證據，避免蓋過五題情境題
    if (followBy) { raw.r += 1; count.r += 1; behaviorAdjust.push("r"); }
    if (behaviors.includes("panic")) { raw.u += 1; count.u += 1; behaviorAdjust.push("u"); }
    const spectrum = {}, zone = {}, high = {}, labels = {};
    ["u","r","m"].forEach(d => {
      spectrum[d] = ((raw[d] - count[d]) / (3 * count[d])) * 100;
      zone[d] = zoneKey(spectrum[d]);
      high[d] = spectrum[d] >= 50;
      labels[d] = dimLabel(d, zone[d], high[d]);
    });
    const typeName = typeOf(high);
    const borderDims = ["u","r","m"].filter(d => zone[d] === "border");
    const neighbors = borderDims.map(d => ({ dim:d, type:typeOf({ ...high, [d]:!high[d] }) }));
    const tensionDims = ["u","r","m"].filter(d => {
      const ss = scores[d].map(x => x.s);
      return ss.length && Math.max(...ss) - Math.min(...ss) === 3;
    });
    const clarityPts = borderDims.length + (tensionDims.length >= 2 ? 1 : 0);
    const clarity = clarityPts === 0 ? "clear" : clarityPts === 1 ? "medium" : "mixed";

    const knowCorrect = KNOW_QS.filter((q, i) => a.know[i] === q.answer).length;
    const knowMissed = KNOW_QS.filter((q, i) => a.know[i] !== q.answer);
    const knowLevel = knowCorrect === 0 ? "starting" : knowCorrect <= 2 ? "basic" : "solid";

    const flags = [];
    const life = has(a.safe[0]) ? LIFE[a.safe[0]] : "early";
    if (has(a.safe[1]) && a.safe[1] <= 1 && life !== "hs") flags.push("fund");
    if (a.safe[2] === 0) flags.push("need");
    if (a.safe[3] === 0) flags.push("debt");

    const risks = [];
    if (a.safe[2] === 1) risks.push("retire");
    ["lever","concentrate"].forEach(c => { if (behaviors.includes(c)) risks.push(c); });
    if (followBy) risks.push("follow");
    if (behaviors.includes("panic")) risks.push("panic");
    if (source === "advisor") risks.push("advisor");

    const practices = (Array.isArray(a.pos[0]) ? a.pos[0] : has(a.pos[0]) ? [a.pos[0]] : [0]).map(i => POS_QS[0].codes[i]);
    const practice = PRACTICE_RANK.find(c => practices.includes(c)) || "none";
    const years = has(a.pos[1]) ? POS_QS[1].codes[a.pos[1]] : null;
    const goal = has(a.pos[2]) ? POS_QS[2].codes[a.pos[2]] : "start";
    const expStage = stageOf(practices, years, 3, true);
    const stage = stageOf(practices, years, knowCorrect);

    // 教練信要引用的題目：偏向最明顯的維度裡，選得最極端的一題
    const quoteDim = ["u","r","m"].reduce((best, d) => Math.abs(spectrum[d] - 50) > Math.abs(spectrum[best] - 50) ? d : best, "u");
    const target = high[quoteDim] ? 4 : 1;
    const rank = (x) => QUOTE_PRIORITY[quoteDim].indexOf(SCALE_QS[x.i].id);
    const pick = scores[quoteDim].slice().sort((x, y) => (Math.abs(x.s - target) - Math.abs(y.s - target)) || (rank(x) - rank(y)))[0];
    const quote = pick ? { dim:quoteDim, side:high[quoteDim] ? "high" : "low", q:SCALE_QS[pick.i], opt:SCALE_QS[pick.i].opts[a.scale[pick.i]].t } : null;

    if (practices.includes("crypto")) risks.push("crypto");
    const plan = buildPlan({ typeName, zone, stage, practice, practices, years, goal, knowCorrect, knowMissed, flags, risks, followBy, safe:a.safe, life });
    const selfType = typeOf({ u:selfSpectrum.u >= 50, r:selfSpectrum.r >= 50, m:selfSpectrum.m >= 50 });
    return { version:VERSION, typeName, raw, spectrum, zone, high, labels, neighbors, borderDims, tensionDims, clarity,
             knowCorrect, knowMissed:knowMissed.map(q => q.topic), knowLevel, flags, risks, behaviors, behaviorAdjust, selfSpectrum, selfType, source, followBy,
             practice, practices, years, goal, stage, expStage, quote, plan, safeAnswer:a.safe[2], fundAnswer:a.safe[1], life,
             scaleS:Object.fromEntries(SCALE_QS.map((q, i) => [q.id, has(a.scale[i]) ? q.opts[a.scale[i]].s : null])) };
  }

  function stageOf(practices, years, knowCorrect, forTone) {
    const experienced = practices.some(c => ["exited","passive","picker","trader","delegated","crypto","family","employee"].includes(c));
    const onlyExited = practices.length === 1 && practices[0] === "exited";
    let stage;
    if (!experienced || years === "lt1" || (onlyExited && !forTone)) stage = "starter";
    else if (years === "y10") stage = "seasoned";
    else stage = "growing";
    // 基礎觀念不足時往前調一階（小挑戰 3 題）：深化需要至少答對 2 題，進階需要至少答對 1 題
    if (stage === "seasoned" && knowCorrect <= 1) stage = "growing";
    if (stage === "growing" && knowCorrect === 0) stage = "starter";
    return stage;
  }

  // 主動交易路線要求「不確定性」與「金錢」都不在交界，且本人不是定期定額；否則改走核心加衛星
  function routeOf(typeName, zone, practices, risks) {
    const base = TYPES[typeName].route;
    if (base === "D" && practices.includes("picker") && !practices.includes("trader") && !practices.includes("passive")) return "B";
    if (base === "D" && (zone.u === "border" || zone.m === "border" || practices.includes("passive") || risks.includes("retire"))) return "C";
    return base;
  }

