  // 教練信：依結果組合，不重抄地圖，第一步與地圖一致
  function buildLetter(r) {
    const paras = [];
    paras.push(LETTER_OPEN[r.stage][r.goal]);
    // 做法比對不一致時，信裡只講比對結果，避免同時出現「適合」與「有衝突」
    const misfit = r.plan.fit && !r.plan.fit.fit;
    if (r.goal === "fit") paras.push(misfit ? r.plan.fit.brief : r.plan.styleBrief);
    if (r.quote) {
      const lead = { u:`在「${r.quote.q.short}」這題，你選的是「${r.quote.opt}」。`, r:`你在「${r.quote.q.short}」這題選了「${r.quote.opt}」，這個選擇很能代表你。`, m:`「${r.quote.opt}」是你在「${r.quote.q.short}」這題的答案。` }[r.quote.dim];
      paras.push(lead + LETTER_QUOTE[r.quote.dim][r.quote.side]);
    }
    const passiveOnly = r.practice === "passive" || !r.plan.invested;
    paras.push((passiveOnly && LETTER_TYPE_PASSIVE[r.typeName]) || LETTER_TYPE[r.typeName]);
    if (r.selfType !== r.typeName) paras.push(`補充一點：只看情境題，你比較接近「${r.selfType}」；把你實際遇過的情況算進去，才變成「${r.typeName}」。想像中的自己和實際的做法有落差很正常，建議以實際做過的事為準來安排學習。`);
    if (r.risks.includes("panic")) paras.push("你這幾年有在大跌時賣掉大部分持股的經驗。這很常見，但也常剛好賣在低點。建議趁現在冷靜，先寫下「什麼情況才賣」，例如錢要拿去用了，而不是價格跌了。");
    if (misfit && r.goal !== "fit") paras.push(r.plan.fit.brief);
    const f = r.plan.first;
    let step;
    if (f.kind === "safety") {
      step = `最先要做的是「${f.t}」：${f.brief}`;
      step += r.plan.invested ? "在那之前，手上的持股不用急著賣，但先別再加碼。" : "預備金存到的那一天，就可以去開證券戶，照學習地圖往下走。";
    } else if (f.kind) {
      step = `最先要做的是「${f.t}」：${f.brief}`;
    } else {
      step = `最先要做的是學習地圖上的第一步「${f.t}」，那裡寫了具體從哪裡開始。`;
      if (f.locked) step += "這一步需要實際下單，先用模擬帳戶或極小的金額。";
    }
    paras.push(step);
    const closeKey = r.stage === "starter" && r.plan.invested ? "starterInvested" : r.stage === "seasoned" && r.practice === "trader" ? "seasonedTrader" : r.stage;
    paras.push(LETTER_CLOSE[closeKey]);
    return paras;
  }

